#!/usr/bin/env -S uv run
"""Build the static site into dist/. Every page is a Page built from the vocabulary in data_model.py."""
import shutil
from pathlib import Path

from data_model import Bold, Link, List, SectionContent, Text
from render import render_page

OUT = Path("dist")

def home():
    return SectionContent([
        Text(["This site is built with ", Bold("Python"), "."]),
        List([Text([f"{n} squared is {n * n}"]) for n in range(1, 6)]),
    ])

def about():
    return SectionContent([
        Text(["Generated by build.py using ", Link("htpy", "https://htpy.dev"), "."]),
    ])

# URL path -> page function. This dict *is* your URL-to-page mapping.
PAGES = {
    "/": home,
    "/about/": about,
}


def main():
    shutil.rmtree(OUT, ignore_errors=True)
    for url, page in PAGES.items():
        path = OUT / url.strip("/") / "index.html"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(str(render_page(page())))
        print(f"{url:12} -> {path}")

if __name__ == "__main__":
    main()
